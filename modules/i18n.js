function interpolate(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

export function normalizeLanguageSetting(value) {
  return LANGUAGE_OPTIONS.includes(value) ? value : "auto";
}

export function detectUiLanguage(extensionApi) {
  const raw = extensionApi?.i18n?.getUILanguage?.() || navigator.language || "en";
  const normalized = String(raw).toLowerCase();
  if (normalized.startsWith("ru")) return "ru";
  if (normalized.startsWith("de")) return "de";
  if (normalized.startsWith("zh")) return "zh-CN";
  return "en";
}

export function resolveLanguage(setting, extensionApi) {
  const normalized = normalizeLanguageSetting(setting);
  return normalized === "auto" ? detectUiLanguage(extensionApi) : normalized;
}

export function createI18n(setting, extensionApi) {
  const language = resolveLanguage(setting, extensionApi);
  const dictionary = STRINGS[language] || STRINGS.en;
  const locale = language === "zh-CN" ? "zh-CN" : language;
  let fiatDisplayNames = null;

  try {
    fiatDisplayNames = new Intl.DisplayNames([locale], { type: "currency", fallback: "code" });
  } catch {
    fiatDisplayNames = null;
  }

  const t = (key, values) => interpolate(dictionary[key] ?? STRINGS.en[key] ?? key, values);

  const currencyName = (currency) => {
    if (!currency) return "";
    if (currency.type === "fiat" && fiatDisplayNames) {
      try {
        const localized = fiatDisplayNames.of(currency.id.toUpperCase());
        if (localized && localized.toUpperCase() !== currency.id.toUpperCase()) return localized;
      } catch {
        // Use catalog fallback below.
      }
    }
    if (language === "zh-CN" && CRYPTO_NAMES_ZH[currency.id]) return CRYPTO_NAMES_ZH[currency.id];
    return currency.name;
  };

  const applyDocument = () => {
    document.documentElement.lang = locale;
    document.title = t("documentTitle");

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", t(element.dataset.i18nTitle));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
  };

  const formatDate = (dateValue) => {
    if (typeof dateValue !== "string" || !dateValue) return t("unknownDate");
    const date = new Date(`${dateValue}T00:00:00Z`);
    if (Number.isNaN(date.getTime())) return t("unknownDate");
    return new Intl.DateTimeFormat(locale, {
      day: "2-digit",
      month: "2-digit",
      year: "numeric",
      timeZone: "UTC"
    }).format(date);
  };

  const formatDateTime = (timestamp) => {
    const date = new Date(timestamp);
    if (Number.isNaN(date.getTime())) return t("unknownDate");
    return new Intl.DateTimeFormat(locale, {
      dateStyle: "short",
      timeStyle: "short"
    }).format(date);
  };

  const formatAge = (milliseconds) => {
    if (!Number.isFinite(milliseconds) || milliseconds < 0) return t("recently");
    const minutes = Math.floor(milliseconds / 60_000);
    if (minutes < 1) return t("justNow");
    if (minutes < 60) return t("minutesAgo", { value: minutes });
    const hours = Math.floor(minutes / 60);
    if (hours < 24) return t("hoursAgo", { value: hours });
    return t("daysAgo", { value: Math.floor(hours / 24) });
  };

  return { language, locale, t, currencyName, applyDocument, formatDate, formatDateTime, formatAge };
}
